/** Scores a short offer for "Голос сделки". */
export function scoreVoice(text: string) {
  const t = text.toLowerCase();
  const meaning = Math.min(100, (t.split(/\s+/).filter(Boolean).length / 25) * 100);
  const unsure = ["может быть", "наверное", "если хотите", "не знаю", "попробую"].filter((w) =>
    t.includes(w),
  ).length;
  const confidence = Math.max(0, 100 - unsure * 30);
  const next =
    /(запис|созвон|встреч|понедельник|вторник|сред|четверг|пятниц|суббот|воскресен|\d{1,2}[:.]\d{2}|завтра|ссылк)/.test(
      t,
    )
      ? 100
      : 0;
  return {
    meaning: Math.round(meaning),
    confidence,
    next,
    total: Math.round((meaning + confidence + next) / 3),
  };
}

/** Heuristic chat review for "Наставник-шпион". */
export function analyzeChat(text: string) {
  const lines = text
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
  const questions = (text.match(/\?/g) ?? []).length;
  const t = text.toLowerCase();
  const hasNext = /(запис|созвон|встреч|время|когда удобно|ссылк|оплат)/.test(t);
  const lastLine = lines[lines.length - 1] ?? "";
  const findings: string[] = [];
  if (questions < 2)
    findings.push(
      "Мало вопросов — вы больше рассказываете, чем узнаёте. Задайте хотя бы 2 открытых вопроса о ситуации клиента.",
    );
  if (!hasNext)
    findings.push("Не предложен следующий шаг: нет даты, времени или ссылки на запись.");
  if (!lastLine.includes("?"))
    findings.push(
      "Инициатива потеряна: последнее сообщение не заканчивается вопросом — диалогу некуда продолжаться.",
    );
  if (/(дорого|подумаю|потом)/.test(t))
    findings.push("Есть возражение — проверьте, уточнили ли вы, что за ним стоит.");
  if (findings.length === 0)
    findings.push("Отличная переписка: есть вопросы, инициатива и следующий шаг.");
  const tips = [
    "Завтра заканчивайте каждое сообщение вопросом.",
    "Завтра предлагайте два варианта времени вместо «когда удобно?».",
    "Завтра спросите клиента: «Что для вас будет результатом?»",
  ];
  return {
    findings,
    tip: tips[(lines.length + questions) % tips.length],
    score: Math.max(0, 100 - (findings.length - (findings[0].startsWith("Отличная") ? 1 : 0)) * 25),
  };
}
